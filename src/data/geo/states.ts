// Geography layer: facts only, no marketing copy.
//
// Per the "District to Metro" roadmap, the state layer is where genuine
// differentiation is cheapest and strongest: professional tax, incorporation
// stamp duty and the Shops & Establishments Act all genuinely differ by state,
// and almost nobody publishes them properly. Copy that *uses* these facts lives
// in src/data/services/copy/*, never here.
//
// VERIFY discipline: a figure nobody has checked against the source is worse
// than a missing figure, because a page that ranks and hands a business owner
// the wrong tax number costs more than it earns. Every entry carries a `verify`
// list naming what a human must confirm before any page built on it flips to
// contentStatus "ready". Run `npm run verify:geo` to print the whole backlog.

export type StateType = "state" | "ut";

export interface ProfessionalTax {
  /** Whether the state levies a tax on professions, trades and employment. */
  levied: boolean;
  /** Plain-language status. Slab figures are deliberately NOT asserted here. */
  note: string;
}

export interface StateEntry {
  name: string;
  slug: string;
  type: StateType;
  /** Two-digit GST state code, the first two digits of every GSTIN issued here. */
  gstStateCode: string;
  /** Registrar of Companies office that incorporations from this state file into. */
  rocOffice: string;
  professionalTax: ProfessionalTax;
  stampDutyNote: string;
  shopsActNote: string;
  /**
   * UTs where the territory and its principal city are the same place, so
   * /service/delhi/delhi is a doubled segment nobody would ever type or link.
   * These render at /service/<state> instead; see locationPath() in src/lib/geo.ts.
   */
  singleSegment?: true;
  /** Alternate spellings that need a permanent redirect to the canonical slug. */
  aliases: string[];
  /** What a human must check against the source before publishing on this entry. */
  verify: string[];
}

